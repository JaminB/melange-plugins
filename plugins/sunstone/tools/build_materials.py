#!/usr/bin/env python3
"""Splice Sunstone's material library (tools/materials) into the lit textured model shaders.

A development tool, not part of the plugin. It rewrites the block between the BEGIN/END MATERIALS markers of
mod/shaders/FixedFunction.FFFragmentMainTexLit.glsl and FixedFunction.FFFragmentMainTexLitCol.glsl with:

  tools/materials/_common.glsl     the inputs and outputs (MatIn, MatOut), helpers, MatSetup (owned by the library)
  tools/materials/<class>.glsl     one snippet per class: MatOut mat_<class>(MatIn m), see tools/materials/README.md
  (generated)                      MatDispatch, a switch on the class id, and the defaults of the fallback classes
  tools/materials/_evaluate.glsl   the tag, the switches and the blend of a snippet's result

and sets both shaders' first line to #version 130 (the shared material maps are a sampler2DArray).

Class ids come from tools/materials/classes.json; a class with no snippet is drawn by generic.glsl.

    python tools/build_materials.py              # rewrite both shaders
    python tools/build_materials.py --check      # exit 1 when a shader is out of date (nothing written)
    python tools/build_materials.py --out x.glsl # write the TexLit shader with the block to x.glsl only (a class
                                                 # worker's candidate; the committed shader is left alone)
    python tools/build_materials.py --table t.json   # also write the class table with each class's defaults
"""
import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PLUGIN = HERE.parent
MATERIALS = HERE / "materials"
SHADERS = {
    "texlit": PLUGIN / "mod" / "shaders" / "FixedFunction.FFFragmentMainTexLit.glsl",
    "texlitcol": PLUGIN / "mod" / "shaders" / "FixedFunction.FFFragmentMainTexLitCol.glsl",
}
BEGIN = "// BEGIN MATERIALS (generated by tools/build_materials.py from tools/materials; do not edit by hand)"
END = "// END MATERIALS"
BLOCK_RE = re.compile(r"// BEGIN MATERIALS.*?// END MATERIALS", re.S)
# The shared material maps (uniform sampler2DArray sunstoneMat, texture()/textureGrad()) need GLSL 1.30; the game's Cg
# vertex programs (GLSL 1.10, gl_TexCoord[]) link with a 1.30 fragment program. Both shaders get this first line.
VERSION = "#version 130"
VERSION_RE = re.compile(r"\A#version[^\n]*")

# The 7 tag parameters, in the order of mg_texTag[0].yzw then mg_texTag[1].xyzw.
PARAMS = ["scale", "strength", "rough", "wear", "tint", "a", "b"]
PARAM_DEFAULTS = {"scale": 1.0, "strength": 1.0, "rough": 0.0, "wear": 0.0, "tint": 0.0, "a": 0.0, "b": 0.0}
# Ranges the tag table accepts (make_tag_table.py checks overrides against them).
PARAM_RANGES = {"scale": (0.05, 16.0), "strength": (0.0, 2.0), "rough": (-1.0, 1.0), "wear": (0.0, 1.0),
                "tint": (0.0, 4.0), "a": (-16.0, 16.0), "b": (-16.0, 16.0)}
GENERIC = "generic"
# What a snippet may not use: derivatives (MatIn has them; a snippet may branch per fragment), its own uniforms (its
# parameters come from the tag), or the output.
FORBIDDEN = [(re.compile(r"\b(dFdx|dFdy|fwidth)\b"), "derivatives (use MatIn's uvDx/uvDy/lumD, MatBumpScreen)"),
             (re.compile(r"\buniform\b"), "uniforms (parameters come from the tag: m.scale, m.p)"),
             (re.compile(r"\b(gl_FragColor|gl_FragData|discard)\b"), "the output (return a MatOut)"),
             (re.compile(r"^\s*#"), "preprocessor lines")]


def load_classes():
    data = json.loads((MATERIALS / "classes.json").read_text(encoding="utf-8"))
    classes = data["classes"]
    ids = [c["id"] for c in classes]
    names = [c["name"] for c in classes]
    if ids != list(range(1, len(ids) + 1)):
        sys.exit("tools/materials/classes.json: ids must run 1..N in order")
    if len(set(names)) != len(names) or GENERIC in names:
        sys.exit("tools/materials/classes.json: duplicate class name, or a class called 'generic'")
    for c in classes:
        if not re.fullmatch(r"[a-z][a-z0-9_]*", c["name"]):
            sys.exit(f"tools/materials/classes.json: bad class name {c['name']!r}")
    fb = data.get("fallback", {})
    for k in ("metal", "matte"):
        if fb.get(k) not in names + [GENERIC]:
            sys.exit(f"tools/materials/classes.json: fallback.{k} must name a class or 'generic'")
    return data


def parse_snippet(path, name):
    """The snippet's text, its @default parameters and @param notes; exits on a malformed snippet."""
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    errors = []
    m = re.search(r"^// @class\s+(\S+)\s*$", text, re.M)
    if not m or m.group(1) != name:
        errors.append(f"needs a '// @class {name}' line")
    defaults = dict(PARAM_DEFAULTS)
    m = re.search(r"^// @default\s+(.*)$", text, re.M)
    if m:
        for kv in m.group(1).split():
            k, _, v = kv.partition("=")
            if k not in PARAMS:
                errors.append(f"@default: unknown parameter {k!r} (known: {', '.join(PARAMS)})")
                continue
            try:
                defaults[k] = float(v)
            except ValueError:
                errors.append(f"@default: {k}={v!r} is not a number")
                continue
            lo, hi = PARAM_RANGES[k]
            if not lo <= defaults[k] <= hi:
                errors.append(f"@default: {k}={v} is outside {lo}..{hi}")
    notes = {k: v.strip() for k, v in re.findall(r"^// @param\s+(\w+):\s*(.*)$", text, re.M)}
    if not re.search(rf"^MatOut mat_{name}\(MatIn m\)\s*\{{", text, re.M):
        errors.append(f"must define 'MatOut mat_{name}(MatIn m) {{' at the start of a line")
    # Strip comments before linting the code.
    code = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    code = re.sub(r"//[^\n]*", "", code)
    for i, line in enumerate(code.split("\n"), 1):
        for rx, why in FORBIDDEN:
            if rx.search(line):
                errors.append(f"line {i}: no {why}")
    # Every top-level declaration carries the snippet's prefix, so snippets never collide.
    prefixes = (f"mat_{name}", f"MAT_{name.upper()}")
    depth = 0
    for i, line in enumerate(code.split("\n"), 1):
        if depth == 0:
            d = re.match(r"\s*(?:const\s+)?(?:struct\s+)?[A-Za-z_]\w*(?:\[\w*\])?\s+([A-Za-z_]\w*)", line)
            if d and not d.group(1).startswith(prefixes) and line.strip():
                errors.append(f"line {i}: top-level name {d.group(1)!r} must start with {prefixes[0]} or {prefixes[1]}")
        depth += line.count("{") - line.count("}")
    if depth != 0:
        errors.append("unbalanced braces")
    if errors:
        sys.exit(f"{path.relative_to(PLUGIN)}:\n  " + "\n  ".join(errors))
    return text.strip("\n"), defaults, notes


def class_table():
    """[{id, name, snippet, defaults{7}, notes}] for id 0 (generic) and every class, and the class data."""
    data = load_classes()
    snippets = {}
    for p in sorted(MATERIALS.glob("*.glsl")):
        if p.name.startswith("_"):
            continue
        name = p.stem
        if name != GENERIC and name not in [c["name"] for c in data["classes"]]:
            sys.exit(f"{p.relative_to(PLUGIN)}: no class {name!r} in tools/materials/classes.json")
        snippets[name] = parse_snippet(p, name)
    if GENERIC not in snippets:
        sys.exit("tools/materials/generic.glsl is missing")
    rows = [{"id": 0, "name": GENERIC, "snippet": GENERIC, "defaults": snippets[GENERIC][1], "notes": snippets[GENERIC][2]}]
    for c in data["classes"]:
        own = c["name"] in snippets
        src = snippets[c["name"] if own else GENERIC]
        rows.append({"id": c["id"], "name": c["name"], "snippet": c["name"] if own else GENERIC,
                     "defaults": src[1], "notes": src[2]})
    return rows, snippets, data


def fmt(v):
    s = f"{v:.6g}"
    return s if any(ch in s for ch in ".e") else s + ".0"


def vec4(vals):
    return "vec4(" + ", ".join(fmt(v) for v in vals) + ")"


def block(rows, snippets, data):
    by_name = {r["name"]: r for r in rows}
    fb_metal = by_name[data["fallback"]["metal"]]["id"]
    fb_matte = by_name[data["fallback"]["matte"]]["id"]
    out = [BEGIN]
    out.append((MATERIALS / "_common.glsl").read_text(encoding="utf-8").replace("\r\n", "\n").strip("\n"))
    out.append("")
    out.append("// ---- snippets (tools/materials/<class>.glsl)")
    for name in [GENERIC] + sorted(n for n in snippets if n != GENERIC):
        out.append(f"// -- {name}.glsl")
        out.append(snippets[name][0])
    out.append("")
    out.append("// ---- generated: class ids (tools/materials/classes.json) and the dispatch")
    out.append(f"const int MAT_CLASSES = {len(data['classes'])};")
    out.append(f"const int MAT_FALLBACK_METAL = {fb_metal};   // {data['fallback']['metal']}")
    out.append(f"const int MAT_FALLBACK_MATTE = {fb_matte};   // {data['fallback']['matte']}")
    own = [r for r in rows if r["id"] > 0 and r["snippet"] != GENERIC]
    drawn_generic = [r["name"] for r in rows if r["id"] > 0 and r["snippet"] == GENERIC]
    out.append("MatOut MatDispatch(int c, MatIn m) {")
    for r in own:
        out.append(f"    if (c == {r['id']}) return mat_{r['name']}(m);")
    if drawn_generic:
        out.append(f"    // generic: 0 and {', '.join(drawn_generic)}")
    out.append(f"    return mat_{GENERIC}(m);")
    out.append("}")
    out.append("// The tag an untagged texture of a fallback class gets: (class, scale, strength, rough), (wear, tint, a, b).")
    out.append("void MatDefaults(int c, out vec4 t0, out vec4 t1) {")
    if fb_metal != fb_matte:
        d = next(x for x in rows if x["id"] == fb_metal)["defaults"]
        out.append(f"    if (c == {fb_metal}) {{ t0 = {vec4([fb_metal, d['scale'], d['strength'], d['rough']])}; "
                   f"t1 = {vec4([d['wear'], d['tint'], d['a'], d['b']])}; return; }}")
    d = by_name[data["fallback"]["matte"]]["defaults"]
    out.append(f"    t0 = {vec4([fb_matte, d['scale'], d['strength'], d['rough']])};")
    out.append(f"    t1 = {vec4([d['wear'], d['tint'], d['a'], d['b']])};")
    out.append("}")
    out.append("")
    out.append((MATERIALS / "_evaluate.glsl").read_text(encoding="utf-8").replace("\r\n", "\n").strip("\n"))
    out.append(END)
    return "\n".join(out)


def splice(text, blk, label):
    norm = text.replace("\r\n", "\n")
    new, n = BLOCK_RE.subn(lambda _: blk, norm)
    if n != 1:
        sys.exit(f"{label}: needs exactly one BEGIN/END MATERIALS block")
    new, n = VERSION_RE.subn(VERSION, new)
    if n != 1:
        sys.exit(f"{label}: must start with a #version line")
    return new


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 when a shader is out of date; write nothing")
    ap.add_argument("--out", help="write the TexLit shader with the new block here instead of mod/shaders")
    ap.add_argument("--out-col", help="write the TexLitCol shader with the new block here instead of mod/shaders")
    ap.add_argument("--table", help="also write the class table (ids, names, snippet, defaults) as JSON here")
    args = ap.parse_args()

    rows, snippets, data = class_table()
    blk = block(rows, snippets, data)
    if args.table:
        Path(args.table).write_text(json.dumps({"params": PARAMS, "classes": rows}, indent=1), encoding="utf-8")
    targets = []
    if args.out or args.out_col:
        if args.out:
            targets.append(("texlit", Path(args.out)))
        if args.out_col:
            targets.append(("texlitcol", Path(args.out_col)))
    else:
        targets = [(k, p) for k, p in SHADERS.items()]
    stale = []
    for key, dest in targets:
        src = SHADERS[key]
        old = src.read_text(encoding="utf-8")
        new = splice(old, blk, src.name)
        if args.check:
            if new != old.replace("\r\n", "\n"):
                stale.append(src.name)
            continue
        crlf = "\r\n" in old and dest == src
        dest.write_text(new.replace("\n", "\r\n") if crlf else new, encoding="utf-8", newline="")
        print(f"{dest}: {len(new.encode())} bytes ({len(blk.encode())} in the materials block)")
    n_own = sum(1 for r in rows if r["id"] > 0 and r["snippet"] != GENERIC)
    if args.check:
        if stale:
            print("out of date (run tools/build_materials.py): " + ", ".join(stale), file=sys.stderr)
            sys.exit(1)
        print("shaders up to date")
    print(f"{len(rows) - 1} classes, {n_own} with their own snippet, the rest generic")


if __name__ == "__main__":
    main()
