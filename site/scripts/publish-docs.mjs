// Step 4: contributor docs under src/content/docs/publish/ (served at /melange-plugins/publish/...):
//   index.md        from CONTRIBUTING.md
//   store-json.md   from schema/store-1.schema.json   (rendered by lib/schema-md.mjs)
//   index-json.md   from schema/index-1.schema.json
//   import-json.md  from schema/import-1.schema.json  (importer recipes, e.g. caravan)
//   policy.md       from policy/* (and the file-type lists in tools/store.py), rendered as lists
import path from 'node:path';
import {
	BASE, DOCS_DIR, REPO_DIR, HardError, Report, blobUrl, cleanDir, editUrl, escapeStrayAngles, exists, firstParagraph,
	frontmatter, gitDate, isMain, readJson, readText, rewriteLinks, runStandalone, sitePageMap, stripH1, treeUrl,
	writeFile,
} from './lib/common.mjs';
import { schemaToMarkdown } from './lib/schema-md.mjs';
import { loadPlugins } from './lib/plugins-data.mjs';

export const PUBLISH_DIR = path.join(DOCS_DIR, 'publish');

export const SCHEMA_PAGES = [
	{ file: 'schema/store-1.schema.json', slug: 'store-json', label: 'store.json' },
	{ file: 'schema/index-1.schema.json', slug: 'index-json', label: 'index.json' },
	{ file: 'schema/import-1.schema.json', slug: 'import-json', label: 'import.json' },
];

function contributingPage(pageMap, report) {
	const src = 'CONTRIBUTING.md';
	const md = readText(path.join(REPO_DIR, src));
	const { title, body } = stripH1(md);
	const text = escapeStrayAngles(rewriteLinks(body, { fromDir: '', pageMap, report })).trim();
	const refs = SCHEMA_PAGES.map((s) => `[${s.label}](${BASE}/publish/${s.slug}/)`).join(', ');
	return [
		frontmatter({
			title: title ?? 'Publish a plugin',
			description: firstParagraph(body),
			editUrl: editUrl(src),
			lastUpdated: gitDate(src),
		}),
		`<!-- Generated by site/scripts/publish-docs.mjs from ${src}. Do not edit. -->`,
		'',
		text,
		'',
		'## Reference',
		'',
		`Field-by-field references: ${refs}. What the automated checks allow and refuse: [policy](${BASE}/publish/policy/).`,
		'',
	].join('\n');
}

function schemaPage({ file, label }) {
	const schema = readJson(path.join(REPO_DIR, file));
	const { title, description, markdown } = schemaToMarkdown(schema, { headingLevel: 2 });
	// The schema's title is a path (plugins/<id>/store.json): one unbreakable token that wraps mid-word on phones, so
	// the page is titled by the short label and the path leads the intro instead.
	const intro = (title && title !== label ? `\`${title}\`. ` : '') + (description ? `${description}\n\n` : '\n\n');
	return [
		frontmatter({
			title: label,
			description: description ? firstParagraph(description) : undefined,
			editUrl: editUrl(file),
			lastUpdated: gitDate(file),
		}),
		`<!-- Generated by site/scripts/publish-docs.mjs from ${file}. Do not edit. -->`,
		'',
		escapeStrayAngles(intro) +
			`Generated from [\`${file}\`](${blobUrl(file)}) (JSON Schema). The validator, \`tools/store.py\`, applies the same rules.`,
		'',
		markdown,
	].join('\n');
}

/** Parses a "one entry per line, # comments" policy file into groups: [{ note, items[] }]. */
function lineGroups(text) {
	const groups = [];
	let note = [];
	let current = null;
	for (const raw of text.split('\n')) {
		const line = raw.trim();
		if (!line) continue;
		if (line.startsWith('#')) {
			note.push(line.replace(/^#+\s?/, ''));
			current = null;
			continue;
		}
		if (!current) {
			current = { note: note.join(' '), items: [] };
			groups.push(current);
			note = [];
		}
		current.items.push(line);
	}
	if (note.length) groups.push({ note: note.join(' '), items: [] });
	return groups;
}

function renderGroups(groups, emptyText) {
	const out = [];
	for (const g of groups) {
		if (g.note) out.push(g.note, '');
		if (g.items.length) out.push(...g.items.map((i) => `- \`${i}\``), '');
	}
	if (!groups.some((g) => g.items.length)) out.push(emptyText, '');
	return out;
}

/** Reads a Python set literal such as FILE_TYPE_EXTENSIONS = {...} out of tools/store.py. */
function pySet(source, name) {
	const m = source.match(new RegExp(`^${name}\\s*=\\s*\\{([^}]*)\\}`, 'm'));
	return m ? [...m[1].matchAll(/"([^"]*)"/g)].map((x) => x[1]) : null;
}

function policyPage(report) {
	const p = (f) => path.join(REPO_DIR, 'policy', f);
	const out = [];
	const list = (f) => (exists(p(f)) ? readJson(p(f)) : []);

	const reserved = exists(p('reserved-ids.txt')) ? lineGroups(readText(p('reserved-ids.txt'))) : [];
	out.push('## Reserved ids', '');
	out.push(`A plugin can't use these ids ([\`policy/reserved-ids.txt\`](${blobUrl('policy/reserved-ids.txt')})).`, '');
	out.push(...renderGroups(reserved, 'None.'));

	out.push('## Executables allow-list', '');
	out.push(
		`A file that looks like a program (by extension, or by an \`MZ\` / ELF header) fails the checks unless it is listed in ` +
			`[\`policy/executables.json\`](${blobUrl('policy/executables.json')}) with its plugin, path and SHA-256.`,
		'',
	);
	const execs = list('executables.json');
	if (execs.length) out.push(...execs.map((e) => `- \`${e.id}\`: \`${e.path}\` (SHA-256 \`${e.sha256}\`)`), '');
	else out.push('None: no plugin ships an executable.', '');

	const store = exists(path.join(REPO_DIR, 'tools', 'store.py')) ? readText(path.join(REPO_DIR, 'tools', 'store.py')) : '';
	const execExt = pySet(store, 'EXECUTABLE_EXTENSIONS');
	const fileExt = pySet(store, 'FILE_TYPE_EXTENSIONS');
	if (execExt) out.push(`Extensions treated as executables: ${execExt.map((e) => `\`${e}\``).join(', ')}.`, '');
	else report.warn('could not read EXECUTABLE_EXTENSIONS from tools/store.py');

	out.push('## Allowed file types', '');
	if (fileExt) out.push(`Files in \`mod/\` must have one of these extensions (or be named \`LICENSE\`): ${fileExt.map((e) => `\`${e}\``).join(', ')}.`, '');
	else report.warn('could not read FILE_TYPE_EXTENSIONS from tools/store.py');
	out.push(`Exceptions for a single file of a single plugin are listed in [\`policy/extra-types.json\`](${blobUrl('policy/extra-types.json')}):`, '');
	const extra = list('extra-types.json');
	if (extra.length) out.push(...extra.map((e) => `- \`${e.id}\`: \`${e.path}\``), '');
	else out.push('None.', '');

	out.push('## Stock game file names', '');
	const stock = exists(p('stock-names.txt')) ? lineGroups(readText(p('stock-names.txt'))) : [];
	out.push(...renderGroups(stock, 'No names are listed yet.'));

	out.push('## Import hosts', '');
	out.push(
		`An importer recipe (\`mod/import.json\`, see [import.json](${BASE}/publish/import-json/)) may only download from these hosts ` +
			`([\`policy/import-hosts.json\`](${blobUrl('policy/import-hosts.json')})):`,
		'',
	);
	const hosts = list('import-hosts.json');
	if (hosts.length) out.push(...hosts.map((h) => `- \`${h}\``), '');
	else out.push('None.', '');

	const dates = ['reserved-ids.txt', 'executables.json', 'extra-types.json', 'stock-names.txt', 'import-hosts.json']
		.map((f) => gitDate(`policy/${f}`))
		.filter(Boolean)
		.sort((a, b) => b - a);
	return [
		frontmatter({
			title: 'Store policy',
			description: 'Reserved ids, the executables allow-list, allowed file types and import hosts the store checks enforce.',
			editUrl: `${treeUrl('policy')}`,
			lastUpdated: dates[0],
		}),
		'<!-- Generated by site/scripts/publish-docs.mjs from policy/* and tools/store.py. Do not edit. -->',
		'',
		`The lists below are read from [\`policy/\`](${treeUrl('policy')}) by \`tools/store.py\`, which every pull request runs. ` +
			'Changing one is a pull request like any other.',
		'',
		...out,
	].join('\n');
}

export async function main({ write = true, data } = {}) {
	const report = new Report('publish-docs');
	const { plugins } = data ?? loadPlugins(report);
	const pageMap = sitePageMap(plugins.map((p) => p.id));
	if (!exists(path.join(REPO_DIR, 'CONTRIBUTING.md'))) throw new HardError('missing CONTRIBUTING.md');
	const pages = { 'index.md': contributingPage(pageMap, report), 'policy.md': policyPage(report) };
	for (const s of SCHEMA_PAGES) {
		if (!exists(path.join(REPO_DIR, s.file))) {
			report.warn(`missing ${s.file}; skipping its page`);
			continue;
		}
		pages[`${s.slug}.md`] = schemaPage(s);
	}
	if (write) {
		cleanDir(PUBLISH_DIR);
		for (const [name, md] of Object.entries(pages)) writeFile(path.join(PUBLISH_DIR, name), md);
	}
	report.summary(`${write ? 'wrote' : 'checked'} ${Object.keys(pages).length} pages in src/content/docs/publish/`);
	return report;
}

if (isMain(import.meta.url)) runStandalone(main);
