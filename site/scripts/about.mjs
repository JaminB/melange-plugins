// Step 5: src/content/docs/about.md from README.md: its opening paragraph, then the Privacy and Licence sections.
import path from 'node:path';
import {
	DOCS_DIR, REPO_DIR, Report, HardError, editUrl, escapeStrayAngles, exists, frontmatter, gitDate, isMain, readText,
	rewriteLinks, runStandalone, sitePageMap, stripH1, writeFile,
} from './lib/common.mjs';
import { loadPlugins } from './lib/plugins-data.mjs';

export const ABOUT_FILE = path.join(DOCS_DIR, 'about.md');
const SECTIONS = [/^privacy$/i, /^licen[cs]e$/i];

/** Splits markdown into { intro, sections: [{ heading, body }] } on H2 headings (outside code fences). */
function h2Sections(md) {
	const lines = md.split('\n');
	const sections = [];
	const intro = [];
	let cur = null;
	let fence = false;
	for (const line of lines) {
		if (/^\s*(```|~~~)/.test(line)) fence = !fence;
		const m = !fence && line.match(/^## +(.+?)\s*#*\s*$/);
		if (m) {
			cur = { heading: m[1], body: [] };
			sections.push(cur);
		} else (cur ? cur.body : intro).push(line);
	}
	return { intro: intro.join('\n').trim(), sections: sections.map((s) => ({ ...s, body: s.body.join('\n').trim() })) };
}

export async function main({ write = true, data } = {}) {
	const report = new Report('about');
	const { plugins } = data ?? loadPlugins(report);
	const src = 'README.md';
	if (!exists(path.join(REPO_DIR, src))) throw new HardError('missing README.md');
	const { body } = stripH1(readText(path.join(REPO_DIR, src)));
	const { intro, sections } = h2Sections(body);
	const parts = [intro];
	for (const re of SECTIONS) {
		const s = sections.find((x) => re.test(x.heading));
		if (!s) {
			report.warn(`README.md has no section matching ${re}`);
			continue;
		}
		parts.push(`## ${s.heading}`, s.body);
	}
	const pageMap = sitePageMap(plugins.map((p) => p.id));
	const text = escapeStrayAngles(rewriteLinks(parts.join('\n\n'), { fromDir: '', pageMap, report }));
	const md = [
		frontmatter({
			title: 'About',
			description: 'What the Melange plugin store is, what it sends over the network (nothing but downloads you ask for), and its licence.',
			editUrl: editUrl(src),
			lastUpdated: gitDate(src),
		}),
		'<!-- Generated by site/scripts/about.mjs from README.md. Do not edit. -->',
		'',
		text,
		'',
	].join('\n');
	if (write) writeFile(ABOUT_FILE, md);
	report.summary(`${write ? 'wrote' : 'checked'} src/content/docs/about.md`);
	return report;
}

if (isMain(import.meta.url)) runStandalone(main);
